def export_text(elements, ports, start='50M', stop='3G', points=301):
    """Use the repository's *exact* netlist commands and retain node names."""
    lines = ['! Generated by Topic7 Circuit GUI',
             f'FREQ START={start} STOP={stop} POINTS={int(points)}', '']
    for p in sorted(ports):
        obj = ports[p]
        z0 = f' Z0={obj["z0"]}' if obj.get('z0') else ''
        lines.append(f'PORT {p} {obj["node"]}{z0}')
    lines.append('')
    for el in elements:
        values = ' '.join(f'{key}={val}' for key, val in el['params'].items())
        lines.append(' '.join([el['type'], el['name'], *el['nodes'], values]).strip())
    return '\n'.join(lines) + '\n'


