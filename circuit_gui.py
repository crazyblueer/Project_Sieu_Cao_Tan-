            f=np.asarray(net.freqs,dtype=float)
            s11=np.empty(len(f));s21=np.empty(len(f))
            for i,frequency in enumerate(f):
                s=solve_netlist_at_freq(net,float(frequency),method='matrix')
                s11[i]=20*np.log10(max(abs(s[0,0]),1e-15))
