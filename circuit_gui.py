from __future__ import annotations
import copy
from pathlib import Path
import tkinter as tk
from tkinter import ttk, filedialog, messagebox, simpledialog
import numpy as np

from netlist import CircuitNetlist, read_netlist, N_NODES, REQUIRED
from solver import solve_netlist_at_freq

DEFAULTS = {
    'RES': {'R': '50'}, 'CAP': {'C': '1p'}, 'IND': {'L': '1n'},
    'TLINE': {'Z0': '50', 'EL': '90', 'F0': '1G'},
    'MLIN': {'W': '2m', 'L': '10m', 'H': '1.6m', 'ER': '4.4'},
    'CLIN': {'Z0E': '70', 'Z0O': '35', 'EL': '90', 'F0': '1G'},
    'STUB': {'Z0': '50', 'EL': '90', 'F0': '1G', 'TERM': 'open'},
    'OPEN': {}, 'SHORT': {}, 'S2P': {'FILE': 'fet.s2p'},
}
COLORS = {'RES': '#b45309', 'CAP': '#2563eb', 'IND': '#059669', 'TLINE': '#7c3aed',
          'MLIN': '#7c3aed', 'CLIN': '#7c3aed', 'STUB': '#6d28d9', 'S2P': '#b91c1c'}


def export_text(elements, ports, start='50M', stop='3G', points=301):
    """Use the repository's *exact* netlist commands and retain node names."""
    lines = ['! Generated by Topic7 Circuit GUI',
             f'FREQ START={start} STOP={stop} POINTS={int(points)}', '']
    for p in sorted(ports):
        obj = ports[p]
        z0 = f' Z0={obj["z0"]}' if obj.get('z0') else ''
        lines.append(f'PORT {p} {obj["node"]}{z0}')
    lines.append('')
    for el in elements:
        values = ' '.join(f'{key}={val}' for key, val in el['params'].items())
        lines.append(' '.join([el['type'], el['name'], *el['nodes'], values]).strip())
    return '\n'.join(lines) + '\n'


class SchematicApp:
    def __init__(self, root):
        self.root = root
        root.title('Topic 7 | S-Matrix Schematic Editor')
        root.geometry('1250x790')
        self.elements = []
        self.ports = {}
        self.positions = {}
        self.current_path = None
        self.start, self.stop, self.points = tk.StringVar(value='50M'), tk.StringVar(value='3G'), tk.StringVar(value='301')
        self.active_pin = None
        self.drag_item = None
        self.drag_origin = None
        self.node_counter = 1
        self.selected = None
        self.pin_coords = {}
        self.pin_hit = []
        self.draw_objects = {}
        self._init_ui()
        candidate = Path(__file__).resolve().parent / 'filter_lc.net'
        if candidate.exists():
            self.open_path(candidate)
        else:
            self.new_document()

    def _init_ui(self):
        top = ttk.Frame(self.root, padding=7)
        top.pack(side='top', fill='x')
        for label, callback in [('New', self.new_document), ('Open netlist', self.open_file),
                                ('Save netlist', self.save_file), ('Run S11/S21', self.simulate),
                                ('Edit selected', self.edit_selected), ('Delete selected', self.delete_selected)]:
            ttk.Button(top, text=label, command=callback).pack(side='left', padx=3)
        ttk.Label(top, text='  START').pack(side='left')
        ttk.Entry(top, textvariable=self.start, width=9).pack(side='left')
        ttk.Label(top, text='STOP').pack(side='left')
        ttk.Entry(top, textvariable=self.stop, width=9).pack(side='left')
        ttk.Label(top, text='POINTS').pack(side='left')
        ttk.Entry(top, textvariable=self.points, width=6).pack(side='left')
        body = ttk.Panedwindow(self.root, orient='horizontal')
        body.pack(fill='both', expand=True)
        side = ttk.Frame(body, width=185, padding=8)
        body.add(side, weight=0)
        ttk.Label(side, text='Add components', font=('', 13, 'bold')).pack(anchor='w', pady=(0, 10))
        for kind in ['RES', 'CAP', 'IND', 'TLINE', 'MLIN', 'CLIN', 'STUB', 'OPEN', 'SHORT', 'S2P']:
            ttk.Button(side, text=f'+ {kind}', command=lambda k=kind: self.add_element(k)).pack(fill='x', pady=2)
        ttk.Separator(side).pack(fill='x', pady=12)
        ttk.Button(side, text='+ External Port', command=self.add_port).pack(fill='x', pady=2)
        ttk.Label(side, text='Instructions', font=('', 12, 'bold')).pack(anchor='w', pady=(15, 5))
        description = ('• Drag the center of a component to move it.\n\n'
                       '• Click two terminal dots to connect them (same electrical node).\n\n'
                       '• Double-click a component to edit name, value and node labels.\n\n'
                       '• Wires indicate shared node identity; visual crossings are not connected.\n\n'
                       '• Save a .net file and run the team solver.')
        ttk.Label(side, text=description, wraplength=170, justify='left').pack(anchor='w')
        self.canvas = tk.Canvas(body, bg='#f8fafc', highlightthickness=0)
        body.add(self.canvas, weight=1)
        self.canvas.bind('<ButtonPress-1>', self.mouse_down)
        self.canvas.bind('<B1-Motion>', self.mouse_move)
        self.canvas.bind('<ButtonRelease-1>', self.mouse_up)
        self.canvas.bind('<Double-Button-1>', self.double_click)
        self.canvas.bind('<Configure>', lambda e: self.redraw())
        self.status = tk.StringVar(value='Ready')
        ttk.Label(self.root, textvariable=self.status, relief='sunken', padding=5).pack(side='bottom', fill='x')

    def _unique_name(self, kind):
        prefix = {'RES':'R', 'CAP':'C', 'IND':'L', 'TLINE':'TL', 'MLIN':'ML', 'CLIN':'CL',
                  'STUB':'ST', 'OPEN':'OP', 'SHORT':'SH', 'S2P':'Q'}[kind]
        used = {e['name'] for e in self.elements}
        n=1
        while f'{prefix}{n}' in used:
            n+=1
        return f'{prefix}{n}'

    def new_node(self):
        used = {n for el in self.elements for n in el['nodes']} | {p['node'] for p in self.ports.values()}
        while f'n{self.node_counter}' in used:
            self.node_counter += 1
        ans = f'n{self.node_counter}'
        self.node_counter += 1
        return ans

    def new_document(self):
        self.elements=[]; self.ports={1:{'node':'in','z0':''},2:{'node':'out','z0':''}}
        self.positions={('port',1):(90,220),('port',2):(690,220)}
        self.current_path=None
        self.selected=None; self.active_pin=None
        self.start.set('50M');self.stop.set('3G');self.points.set('301')
        self.redraw()

    def open_file(self):
        path = filedialog.askopenfilename(filetypes=[('Netlist','*.net *.txt'),('All files','*.*')])
        if path: self.open_path(Path(path))

    def open_path(self,path):
        try:
            net = read_netlist(str(path))
            self.elements=copy.deepcopy(net.elements)
            self.ports={p:{'node':node,'z0':str(net.port_z0.get(p,''))} for p,node in net.external_ports.items()}
            # S2P cache objects remain from read_netlist; this GUI only writes text on save
            from components import to_si
            self.start.set(f'{float(net.freqs[0]):.12g}')
            self.stop.set(f'{float(net.freqs[-1]):.12g}')
            self.points.set(str(len(net.freqs)))
            self.positions={}
            for i,el in enumerate(self.elements):
                self.positions[('el',el['name'])]=(200+(i%4)*175,175+(i//4)*125)
            for i,p in enumerate(sorted(self.ports)):
                self.positions[('port',p)]=(85+(i%2)*820,75+(i//2)*80)
            self.current_path=Path(path)
            self.selected=None; self.active_pin=None
            self.status.set(f'Loaded {path.name} | {len(self.elements)} components')
            self.redraw()
        except Exception as ex:
            messagebox.showerror('Netlist error',str(ex))

    def _validate(self):
        from components import to_si
        raw=export_text(self.elements,self.ports,self.start.get(),self.stop.get(),int(self.points.get()))
        net = CircuitNetlist()
        net.base_dir = str((self.current_path or (Path(__file__).resolve().parent/'untitled.net')).resolve().parent)
        # parse_text accesses S2P files using base_dir
        net.parse_text(raw)
        return net,raw

    def save_file(self):
        path=filedialog.asksaveasfilename(defaultextension='.net',filetypes=[('Netlist','*.net')],
                                          initialfile=(self.current_path.name if self.current_path else 'circuit_gui.net'))
        if not path: return
        try:
            # For S2P paths use the output file directory to resolve relative filenames.
            raw=export_text(self.elements,self.ports,self.start.get(),self.stop.get(),int(self.points.get()))
            check=CircuitNetlist(); check.base_dir=str(Path(path).resolve().parent);check.parse_text(raw)
            Path(path).write_text(raw,encoding='utf-8')
            self.current_path=Path(path)
            self.status.set(f'Saved: {path}')
        except Exception as ex:
            messagebox.showerror('Cannot save',str(ex))

    def simulate(self):
        try:
            net,_=self._validate()
            if len(net.external_ports)<2: raise ValueError('Need at least 2 external PORTs')
            freqs=np.asarray(net.freqs)
            s11=[];s21=[]
            for f in freqs:
                s=solve_netlist_at_freq(net,float(f),method='matrix')
                s11.append(20*np.log10(max(abs(s[0,0]),1e-15)))
                s21.append(20*np.log10(max(abs(s[1,0]),1e-15)))
            import matplotlib.pyplot as plt
            fig,ax=plt.subplots(figsize=(9,5))
            ax.plot(freqs/1e9,s11,label='S11 (dB)')
            ax.plot(freqs/1e9,s21,label='S21 (dB)')
            ax.set(xlabel='Frequency (GHz)',ylabel='Magnitude (dB)',title='Simulation via TEAM connection matrix')
            ax.grid(True,alpha=.3);ax.legend();fig.tight_layout()
            self.status.set(f'Simulation complete: {len(freqs)} frequencies')
            plt.show(block=False)
        except Exception as ex:
            messagebox.showerror('Simulation error',str(ex))

    def add_element(self,kind):
        name=self._unique_name(kind)
        nodes=[self.new_node() for _ in range(N_NODES[kind])]
        el={'type':kind,'name':name,'nodes':nodes,'params':DEFAULTS[kind].copy()}
        self.elements.append(el)
        self.positions[('el',name)]=(220+len(self.elements)*17,230+len(self.elements)*11)
        self.selected=('el',name)
        self.redraw()
        self.edit_selected()

    def add_port(self):
        p=max(self.ports,default=0)+1
        self.ports[p]={'node':self.new_node(),'z0':''}
        self.positions[('port',p)]=(100,85+75*p)
        self.redraw()

    def edit_selected(self):
        if not self.selected: return
        key=self.selected
        if key[0]=='port':
            p=key[1]; data=self.ports[p]
            node=simpledialog.askstring('Port node',f'PORT {p}: node',initialvalue=data['node'],parent=self.root)
            if node is None:return
            if not node.strip() or ' ' in node: return messagebox.showerror('Invalid','Node name must not contain spaces')
            z=simpledialog.askstring('Port Z0',f'PORT {p}: Z0 (blank = 50)',initialvalue=data.get('z0',''),parent=self.root)
            if z is None:return
            data.update(node=node.strip(),z0=z.strip())
        else:
            el=next(e for e in self.elements if e['name']==key[1])
            old=el['name']
            name=simpledialog.askstring('Component',f'{el["type"]} name',initialvalue=old,parent=self.root)
            if name is None:return
            if not name.strip() or any(e['name']==name.strip() for e in self.elements if e is not el):
                return messagebox.showerror('Invalid','Empty or duplicate component name')
            nodes=simpledialog.askstring('Node names',f'{el["type"]}: {len(el["nodes"])} nodes separated by spaces\nUse 0 for ground.',
                                         initialvalue=' '.join(el['nodes']),parent=self.root)
            if nodes is None:return
            split=nodes.split()
            if len(split)!=len(el['nodes']):return messagebox.showerror('Invalid','Incorrect number of nodes')
            param_text=' '.join(f'{k}={v}' for k,v in el['params'].items())
            params=simpledialog.askstring('Parameters','KEY=value separated by spaces',initialvalue=param_text,parent=self.root)
            if params is None:return
            try:
                newparams=dict(token.split('=',1) for token in params.split())
                if any(k not in newparams for k in REQUIRED[el['type']]):raise ValueError('Missing required parameters')
            except ValueError as ex:return messagebox.showerror('Invalid',str(ex))
            el.update(name=name.strip(),nodes=split,params=newparams)
            self.positions[('el',el['name'])]=self.positions.pop(('el',old),(200,200))
            self.selected=('el',el['name'])
        self.redraw()

    def delete_selected(self):
        if not self.selected:return
        key=self.selected
        if key[0]=='el':self.elements=[e for e in self.elements if e['name']!=key[1]]
        else:self.ports.pop(key[1],None)
        self.positions.pop(key,None);self.selected=None;self.redraw()

    def _center(self,key):return self.positions.get(key,(150,150))

    def redraw(self):
        if not hasattr(self,'canvas'):return
        self.canvas.delete('all')
        self.pin_hit=[];self.pin_coords={}
        # geometric terminals: each pin represents one named node
        for el in self.elements:
            key=('el',el['name']);x,y=self._center(key);count=len(el['nodes'])
            col=COLORS.get(el['type'],'#475569')
            outline='#f97316' if self.selected==key else col
            self.canvas.create_rectangle(x-49,y-23,x+49,y+23,fill='#fff',outline=outline,width=2)
            self.canvas.create_text(x,y-5,text=f'{el["type"]} {el["name"]}',fill='#0f172a',font=('',10,'bold'))
            detail=' '.join(f'{k}={v}' for k,v in el['params'].items())
            self.canvas.create_text(x,y+12,text=(detail[:23]+'…') if len(detail)>24 else detail,fill='#475569',font=('',8))
            for i,node in enumerate(el['nodes']):
                if count==1: px,py=x,y+30
                elif count==2: px,py=(x-63,y) if i==0 else (x+63,y)
                else: px,py=x-38+(76*i/(count-1)),y+34
                self.canvas.create_line(x+(-49 if count==2 and i==0 else 49 if count==2 else 0),
                                        y+(23 if count!=2 else 0),px,py,fill=col,width=2)
                self._pin((key,i),node,px,py)
        for p,data in self.ports.items():
            key=('port',p);x,y=self._center(key)
            self.canvas.create_oval(x-25,y-20,x+25,y+20,fill='#dbeafe',outline='#2563eb',width=2)
            self.canvas.create_text(x,y,text=f'P{p}',fill='#1e40af',font=('',11,'bold'))
            self._pin((key,0),data['node'],x+38,y)
        # connect pins sharing the same node, via Manhattan spanning chain
        grouping={}
        for pin,(node,px,py) in self.pin_coords.items():
            if node.upper() not in ('0','GND'):grouping.setdefault(node,[]).append((px,py))
        for node,locs in grouping.items():
            if len(locs)<2:continue
            anchor=locs[0]
            for pos in locs[1:]:
                ax,ay=anchor;bx,by=pos
                self.canvas.create_line(ax,ay,bx,ay,bx,by,fill='#64748b',width=2,arrow='none')
        # draw dots LAST so wires do not cover connection handles
        for pin,(node,x,y) in self.pin_coords.items():
            fill='#ef4444' if self.active_pin==pin else ('#111827' if node not in ('0','GND') else '#059669')
            self.canvas.create_oval(x-6,y-6,x+6,y+6,fill=fill,outline='white',width=1.5)
            self.canvas.create_text(x,y+15,text=node,fill='#475569',font=('',8))

    def _pin(self,pin,node,x,y):
        self.pin_coords[pin]=(node,x,y)
        self.pin_hit.append((pin,x,y))

    def _pin_at(self,x,y):
        for pin,px,py in reversed(self.pin_hit):
            if (px-x)**2+(py-y)**2<=13**2:return pin
        return None

    def _item_at(self,x,y):
        for key,(cx,cy) in reversed(list(self.positions.items())):
            if abs(x-cx)<(50 if key[0]=='el' else 25) and abs(y-cy)<24:return key
        return None

    def _node_for_pin(self,pin):
        key,index=pin
        if key[0]=='port':return self.ports[key[1]]['node']
        return next(e for e in self.elements if e['name']==key[1])['nodes'][index]

    def _merge_nodes(self,source,destination):
        if source==destination:return
        # Clicking a ground terminal first makes the new node grounded.
        for el in self.elements:
            el['nodes']=[source if n==destination else n for n in el['nodes']]
        for p in self.ports.values():
            if p['node']==destination:p['node']=source

    def mouse_down(self,e):
        pin=self._pin_at(e.x,e.y)
        if pin:
            if self.active_pin is None:
                self.active_pin=pin;self.status.set(f'Select second terminal to connect to {self._node_for_pin(pin)}')
            else:
                try:
                    a=self._node_for_pin(self.active_pin);b=self._node_for_pin(pin)
                    if a.upper() in ('0','GND') and b.upper() in ('0','GND'):pass
                    elif a.upper() in ('0','GND'):self._merge_nodes('0',b)
                    elif b.upper() in ('0','GND'):self._merge_nodes('0',a)
                    else:self._merge_nodes(a,b)
                    self.status.set(f'Connected node {b} to {a}')
                except Exception as ex:self.status.set(f'Cannot connect: {ex}')
                self.active_pin=None
            self.drag_item=None;self.redraw();return
        self.active_pin=None
        self.drag_item=self._item_at(e.x,e.y)
        self.selected=self.drag_item
        self.drag_origin=(e.x,e.y)
        self.redraw()

    def mouse_move(self,e):
        if not self.drag_item or self.drag_origin is None:return
        dx=e.x-self.drag_origin[0];dy=e.y-self.drag_origin[1]
        x,y=self._center(self.drag_item)
        self.positions[self.drag_item]=(max(60,x+dx),max(55,y+dy))
        self.drag_origin=(e.x,e.y)
        self.redraw()

    def mouse_up(self,e):self.drag_item=None;self.drag_origin=None
    def double_click(self,e):
        item=self._item_at(e.x,e.y)
        if item:self.selected=item;self.edit_selected()


if __name__=='__main__':
    root=tk.Tk()
