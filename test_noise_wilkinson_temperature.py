"""Wilkinson 3-port: effect of temperature of a matched load on port 3.

Run beside noise_analysis.py, test_noise_wilkinson.py and wilkinson.net.
Port 1 is a matched source at T0, port 2 a noiseless matched receiver.
Port 3 is a matched 50-ohm resistor at temperature Tload.
No claim is made that non-290 K results are a standard device noise figure.
"""
from pathlib import Path
import csv
import numpy as np
from scipy.constants import Boltzmann as KB
from netlist import read_netlist
from noise_analysis import analyze_passive_noise, T0

ROOT = Path(__file__).resolve().parent
OUT = ROOT / 'results_noise'
OUT.mkdir(exist_ok=True)
NET = read_netlist(str(ROOT / 'wilkinson.net'))
TEMPERATURES = (77.0, 290.0, 500.0)


def evaluate(frequency_hz, load_temperature):
    d = analyze_passive_noise(NET, frequency_hz, temperature=T0)
    S, C = d['S'], d['C']
    g = abs(S[1, 0]) ** 2
    if g <= 1e-15:
        raise ValueError('Transfer gain too small for input-referred results')
    # Noise generated by Wilkinson device at 290 K.
    own = max(0.0, float(C[1, 1].real))
    # Noise emitted by matched load on port 3, transferred to port 2.
    load = KB * load_temperature * abs(S[1, 2]) ** 2
    # Noise from matched source on port 1 at reference T0.
    source = KB * T0 * g
    total = source + own + load
    # Input-referred noise temperature of system excluding source's noise.
    te_equiv = (own + load) / (KB * g)
    # System noise ratio relative to T0, NOT DUT noise figure if Tload != T0.
    ratio_db = 10 * np.log10(total / source)
    return {
        'freq_GHz': frequency_hz / 1e9,
        'Tload_K': load_temperature,
        'gain': g,
        'S23_abs2': abs(S[1, 2]) ** 2,
        'own_W_Hz': own,
        'load_W_Hz': load,
        'source_W_Hz': source,
        'total_W_Hz': total,
        'Te_equivalent_K': te_equiv,
        'total_to_source_dB': ratio_db,
    }


def main():
    freqs = np.linspace(1.8e9, 3.0e9, 241)
    rows = [evaluate(f, t) for t in TEMPERATURES for f in freqs]
    output = OUT / 'wilkinson_load_temperature.csv'
    with output.open('w', newline='') as f:
        writer = csv.DictWriter(f, fieldnames=list(rows[0]))
        writer.writeheader()
        writer.writerows(rows)

    print('Wilkinson device temperature = 290 K; matched load at port 3')
    for f in (1.8e9, 2.4e9, 3.0e9):
        print(f'\nf={f/1e9:.1f} GHz')
        for t in TEMPERATURES:
            r = evaluate(f, t)
            print(f'  Tload={t:5.0f} K  |S23|^2={r["S23_abs2"]:.4g}'
                  f'  load C22={r["load_W_Hz"]:.4e} W/Hz'
                  f'  Te={r["Te_equivalent_K"]:.3f} K'
                  f'  total/source={r["total_to_source_dB"]:.6f} dB')

    # Independent of any network noise model: a matched load must contribute
    # kB*T*|S23|^2, hence the temperature slope is exactly kB*|S23|^2.
    for f in (1.8e9, 2.4e9, 3.0e9):
        cold, hot = evaluate(f, 77.), evaluate(f, 500.)
        expected = KB * (500. - 77.) * cold['S23_abs2']
        actual = hot['load_W_Hz'] - cold['load_W_Hz']
        assert np.isclose(actual, expected, rtol=1e-12, atol=1e-33)
        assert hot['total_W_Hz'] >= cold['total_W_Hz']
    print('\nPASS: termination-temperature noise transfer identity')
    print('CSV:', output)

    try:
        import matplotlib.pyplot as plt
        fig, ax = plt.subplots(figsize=(8, 4.6))
        for t in TEMPERATURES:
            subset = [r for r in rows if r['Tload_K'] == t]
            ax.plot([r['freq_GHz'] for r in subset],
                    [r['total_to_source_dB'] for r in subset],
                    label=f'Load {t:g} K')
        ax.axvline(2.4, ls='--', alpha=0.5)
        ax.set(xlabel='Frequency (GHz)', ylabel='Total output noise / source output noise (dB)',
               title='Wilkinson: matched port-3 load temperature')
        ax.grid(alpha=0.3)
        ax.legend()
        fig.tight_layout()
        plot = OUT / 'wilkinson_load_temperature.png'
        fig.savefig(plot, dpi=180)
        plt.close(fig)
        print('Plot:', plot)
    except ImportError:
        print('matplotlib not installed: CSV saved, PNG skipped')


if __name__ == '__main__':
    main()
