"""Topic 7: correlated noise waves for an active (S2P) amplifier network.

Requires netlist.py, engine.py, components.py, noise_analysis.py from the repo.
Z0 is one positive real reference for EVERY internal/external port (default 50 ohms).
All passive blocks at temperature K; S2P noise set by EXPLICIT assumed data.
The example default values below are ILLUSTRATIVE, NOT properties of fet.s2p.

S2P S data alone do not determine the transistor's noise covariance.
"""
from __future__ import annotations
import numpy as np
from scipy.constants import Boltzmann as KB
from engine import block_diag
from noise_analysis import passive_noise_covariance, T0

# EXAMPLE ONLY, independent of frequency, not extracted from fet.s2p!
EXAMPLE_NOISE = dict(nfmin_db=1.5, rn_ohm=15.0,
                     gamma_opt=0.30*np.exp(-1j*np.pi/4))


def f_from_noise_params(gamma_s, nfmin_db, rn_ohm, gamma_opt, z0=50.):
    """Standard 4-noise-parameter expression, z0 positive real."""
    g = complex(gamma_s); opt = complex(gamma_opt)
    if abs(g) >= 1 or abs(opt) >= 1:
        raise ValueError('Gamma source/optimum must be strictly inside unit circle')
    if rn_ohm < 0 or nfmin_db < 0 or z0 <= 0:
        raise ValueError('Invalid noise parameters')
    return 10**(nfmin_db/10) + (4*rn_ohm/z0)*abs(g-opt)**2 / ((1-abs(g)**2)*abs(1+opt)**2)


def nf_from_wave_covariance(s, c, gamma_s=0j, t0=T0):
    """F for 2-port with matched noiseless output and source at reference T0.

    Source reflection gamma_s affects signal gain and internal c1 feedback.
    """
    s = np.asarray(s, complex); c = np.asarray(c, complex)
    g = complex(gamma_s)
    if s.shape != (2,2) or c.shape != (2,2) or abs(g) >= 1:
        raise ValueError('Requires two ports and passive source reflection |Gamma|<1')
    d = 1-g*s[0,0]
    transfer = s[1,0]/d
    source_out = KB*t0*(1-abs(g)**2)*abs(transfer)**2
    if source_out <= 1e-60:
        raise ValueError('Output source-noise gain too small')
    q = g*transfer
    noise_row = np.array([q, 1], complex)
    own_out = float(np.real(noise_row @ c @ noise_row.conj()))
    return 1 + own_out / source_out


def noise_params_to_c(s, nfmin_db, rn_ohm, gamma_opt, z0=50., t0=T0):
    """Reconstruct Hermitian two-port wave-noise C from 4 noise parameters.

    Fit four REAL unknowns C11,C22,Re(C12),Im(C12) to analytic F(Gamma)
    using several independent source impedances, rather than modifying S.
    """
    s = np.asarray(s, complex)
    if s.shape != (2,2):
        raise ValueError('Requires a 2x2 transistor S')
    if abs(s[1,0]) < 1e-12:
        raise ValueError('S21 too small for parameter conversion')
    samples = [0, .2, -.2, .2j, -.2j, .45*np.exp(.3j), .45*np.exp(1.5j),
               .6*np.exp(-1.2j), .65*np.exp(2.1j)]
    a, rhs = [], []
    for g in samples:
        tr = s[1,0]/(1-g*s[0,0]); q = g*tr
        # real([q,1] C [q,1]^H) = |q|^2*C11 + C22 + 2 Re(q*C12)
        a.append([abs(q)**2, 1., 2*q.real, -2*q.imag])
        f = f_from_noise_params(g, nfmin_db, rn_ohm, gamma_opt, z0)
        rhs.append((f-1)*(1-abs(g)**2)*abs(tr)**2)
    a = np.array(a, float); rhs = np.array(rhs, float)
    x, _, rank, _ = np.linalg.lstsq(a, rhs, rcond=None)
    if rank != 4 or not np.allclose(a@x, rhs, atol=1e-8, rtol=1e-8):
        raise ValueError('Noise parameter conversion failed (inconsistent model)')
    c = KB*t0*np.array([[x[0], x[2]+1j*x[3]],
                       [x[2]-1j*x[3], x[1]]])
    eig = np.linalg.eigvalsh(c/(KB*t0))
    if eig.min() < -1e-9:
        raise ValueError('Specified noise parameters result in non-PSD noise covariance; '
                         'choose a physically consistent set')
    return (c+c.conj().T)/2


def _block_diagonal(matrices):
    out = np.zeros((sum(m.shape[0] for m in matrices),)*2, complex)
    start = 0
    for m in matrices:
        length = m.shape[0]
        out[start:start+length,start:start+length] = m
        start += length
    return out


def analyze_amplifier(net, freq_hz, noise_models, temperature=T0, z0=50.):
    """Reduce all S & C blocks through original netlist connectivity.

    noise_models = {'Q1': {'nfmin_db':..., 'rn_ohm':..., 'gamma_opt':...}}
    C_OUT excludes external source/load noise, but includes internally generated noise.
    """
    if not isinstance(z0, (int, float)) or z0 <= 0:
        raise ValueError('Only equal positive real reference impedances supported')
    if temperature <= 0:
        raise ValueError('Temperature must be positive')
    blocks, connections, ext, pin_z0, ext_z0 = net.build_network(freq_hz, z0)
    if any(abs(z-z0)>1e-9 for z in ext_z0):
        raise ValueError('External Z0 differs from common real z0')
    s_all, labels = block_diag(blocks)
    c_blocks = []
    for s, pins in blocks:
        name = pins[0].rsplit('_p',1)[0]
        # Element block labels generated by netlist.build_network are <name>_pN.
        is_s2p = any(e['name']==name and e['type']=='S2P' for e in net.elements)
        if is_s2p:
            if name not in noise_models:
                raise ValueError(f'S2P {name} is missing explicit noise model')
            c = noise_params_to_c(s, **noise_models[name], z0=z0, t0=T0)
        else:
            c = passive_noise_covariance(s, temperature=temperature)
        c_blocks.append(c)
    c_all = _block_diagonal(c_blocks)
    # External labels are not pins of S block; map them to their neighboring pins.
    external = set(ext); external_to_pin = {}; internal_pairs=[]
    for p,q in connections:
        if p in external:
            external_to_pin[p]=q
        elif q in external:
            external_to_pin[q]=p
        else:
            internal_pairs.append((labels.index(p), labels.index(q)))
    if set(external_to_pin) != external:
        raise ValueError('An external port was not mapped')
    inside = sorted({i for pair in internal_pairs for i in pair})
    outside = [i for i in range(len(labels)) if i not in inside]
    gamma = np.zeros((len(inside),len(inside)),complex)
    ii = {i:j for j,i in enumerate(inside)}
    for p,q in internal_pairs:
        gamma[ii[p],ii[q]] = gamma[ii[q],ii[p]] = 1
    s_ee=s_all[np.ix_(outside,outside)]
    s_ei=s_all[np.ix_(outside,inside)]
    s_ie=s_all[np.ix_(inside,outside)]
    s_ii=s_all[np.ix_(inside,inside)]
    if inside:
        # H = S_EI @ Gamma @ inv(I - S_II @ Gamma)
        h=np.linalg.solve((np.eye(len(inside))-s_ii@gamma).T,(s_ei@gamma).T).T
    else:
        h=np.empty((len(outside),0),complex)
    permutation=outside+inside
    c_perm=c_all[np.ix_(permutation,permutation)]
    e=np.hstack((np.eye(len(outside)),h))
    s_out=s_ee+h@s_ie
    c_out=e@c_perm@e.conj().T
    # Return ports in PORT order from the netlist, not block creation order
    perm=[outside.index(labels.index(external_to_pin[p])) for p in ext]
    s_out=s_out[np.ix_(perm,perm)]
    c_out=c_out[np.ix_(perm,perm)]
    if len(ext)!=2:
        raise ValueError('This amplifier test requires exactly two external ports')
    f=nf_from_wave_covariance(s_out,c_out,0j,T0)
    return dict(S=s_out,C=c_out,F=float(f),NF_dB=float(10*np.log10(f)),
                frequency_Hz=float(freq_hz),noise_parameters_assumed=True)
